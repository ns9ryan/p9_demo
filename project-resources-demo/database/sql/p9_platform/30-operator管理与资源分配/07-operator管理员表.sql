-- 文件用途:
-- 用于维护 operator 的管理员。
BEGIN;
  CREATE TABLE PUBLIC.operator_admin (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 所属 operator 本地主键
    operator_id BIGINT NOT NULL,
    -- 账号
    username VARCHAR (64) NOT NULL,
    -- 密码
    password VARCHAR (64) NOT NULL,
    -- 显示名称
    display_name VARCHAR (100) NOT NULL,
    -- 状态: 1启用，2停用
    status SMALLINT NOT NULL DEFAULT 1,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_operator_admin PRIMARY KEY (id),
    CONSTRAINT uk_operator_admin_operator_username UNIQUE (operator_id, username),
    CONSTRAINT fk_operator_admin_operator FOREIGN KEY (operator_id) REFERENCES PUBLIC.OPERATOR (id)
  );

  -- 用于按 operator 和域名类型查询域名
  COMMENT ON COLUMN PUBLIC.operator_admin.id IS '主键ID';
  COMMENT ON COLUMN PUBLIC.operator_admin.operator_id IS '所属 operator 本地主键';
  COMMENT ON TABLE PUBLIC.operator_admin IS '总网 operator 管理员表';
  COMMENT ON COLUMN PUBLIC.operator_admin.username IS '账号';
  COMMENT ON COLUMN PUBLIC.operator_admin.password IS '密码';
  COMMENT ON COLUMN PUBLIC.operator_admin.display_name IS '显示名称';
  COMMENT ON COLUMN PUBLIC.operator_admin.status IS '状态: 1启用，2停用';
  COMMENT ON COLUMN PUBLIC.operator_admin.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.operator_admin.updated_at IS '更新时间';
  COMMIT;