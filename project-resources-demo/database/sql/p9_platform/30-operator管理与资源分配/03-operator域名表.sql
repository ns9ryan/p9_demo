-- 文件用途：
-- 用于维护各 operator 不同访问用途的域名
-- 厅后台、代理后台和 H5 会员端通过访问域名识别所属 operator
-- 当前一个域名只能对应一个访问用途
-- 同一个有效域名不能同时绑定多个 operator
BEGIN;
  CREATE TABLE PUBLIC.operator_domain (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- operator ID
    -- 关联 operator.id
    operator_id BIGINT NOT NULL,
    -- operator 全局唯一标识
    -- 用于跨数据库、跨服务、RPC、调度任务、日志和事件识别
    operator_code VARCHAR (32) NOT NULL,
    -- 域名
    -- 只保存域名本身，不包含协议、端口、路径和查询参数
    -- 写入时统一转换为小写并去除首尾空格
    domain_name VARCHAR (253) NOT NULL,
    -- 域名用途
    -- 1厅后台
    -- 2代理后台
    -- 3H5会员端
    -- 4其他业务入口
    domain_type SMALLINT NOT NULL,
    -- 域名状态
    -- 1启用
    -- 2停用
    status SMALLINT NOT NULL DEFAULT 1,
    -- 创建该域名的总网后台用户ID
    -- 逻辑关联 sys_user.id
    created_by BIGINT NOT NULL,
    -- 最后修改该域名的总网后台用户ID
    -- 逻辑关联 sys_user.id
    updated_by BIGINT,
    -- 总网内部备注
    remark VARCHAR (1000),
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_operator_domain PRIMARY KEY (id),
    -- 同一个 operator 不能重复保存相同域名
    CONSTRAINT uk_operator_domain_operator_name UNIQUE (operator_id, domain_name),
    CONSTRAINT fk_operator_domain_operator FOREIGN KEY (operator_id) REFERENCES PUBLIC.OPERATOR (id),
    CONSTRAINT ck_operator_domain_name_not_blank CHECK (BTRIM(domain_name) <> ''),
    -- 域名必须以小写格式保存，并且不能包含首尾空格
    CONSTRAINT ck_operator_domain_name_normalized CHECK (domain_name = LOWER(BTRIM(domain_name))),
    -- 域名不能包含协议、端口、路径、查询参数或空格
    CONSTRAINT ck_operator_domain_name_format CHECK (
      domain_name NOT LIKE'%://%'
      AND domain_name NOT LIKE'%/%'
      AND domain_name NOT LIKE'%:%'
      AND domain_name NOT LIKE'%?%'
      AND domain_name NOT LIKE'%#%'
      AND domain_name !~ '\s'
    ),
    CONSTRAINT ck_operator_domain_type CHECK (domain_type IN (1, 2, 3, 4)),
    CONSTRAINT ck_operator_domain_status CHECK (status IN (1, 2)),
    CONSTRAINT ck_operator_domain_remark CHECK (remark IS NULL OR BTRIM(remark) <> '')
  );
  
  -- 同一个有效域名不能同时绑定多个 operator
  -- 域名停用后允许重新绑定给其他 operator
  CREATE UNIQUE INDEX uk_operator_domain_active_name ON PUBLIC.operator_domain (domain_name)
  WHERE
    status = 1;
    
  -- 用于查询 operator 不同用途的域名
  CREATE INDEX idx_operator_domain_operator_type ON PUBLIC.operator_domain (operator_id, domain_type);
  COMMENT ON TABLE PUBLIC.operator_domain IS '总网 operator 域名表';
  COMMENT ON COLUMN PUBLIC.operator_domain.id IS 'operator 域名记录本地主键';
  COMMENT ON COLUMN PUBLIC.operator_domain.operator_id IS 'operator ID，关联 operator.id';
  COMMENT ON COLUMN PUBLIC.operator_domain.domain_name IS '访问域名，只保存小写域名，不包含协议、端口、路径和查询参数';
  COMMENT ON COLUMN PUBLIC.operator_domain.domain_type IS '域名用途：1厅后台，2代理后台，3H5会员端，4其他业务入口';
  COMMENT ON COLUMN PUBLIC.operator_domain.status IS '域名状态：1启用，2停用';
  COMMENT ON COLUMN PUBLIC.operator_domain.created_by IS '创建该域名的总网后台用户ID，逻辑关联 sys_user.id';
  COMMENT ON COLUMN PUBLIC.operator_domain.updated_by IS '最后修改该域名的总网后台用户ID，逻辑关联 sys_user.id';
  COMMENT ON COLUMN PUBLIC.operator_domain.remark IS '总网内部备注';
  COMMENT ON COLUMN PUBLIC.operator_domain.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.operator_domain.updated_at IS '最后更新时间';
  COMMIT;
  
  -- 需要讨论的问题：
  -- 1. 当前 operator_domain 与 operator 位于同一个 p9_platform 数据库，
  --    因此 operator_id 通过本地ID关联 operator.id
  --    是否需要改为使用 operator_code 等稳定唯一标识关联
  --
  -- 2. domain_type 中是否需要保留“4其他业务入口”
  --    如果目前没有明确业务用途，可以先删除，
  --    后续出现实际入口时再增加对应类型
  --
  -- 3. 同一个 operator 在同一种域名类型下，
  --    是否只允许配置一个有效域名
  --    如果每种类型永久只允许一个域名，
  --    并且不需要备用域名、停用状态和替换记录，
  --    是否取消本表并将固定域名字段放入 operator_profile
  --    如果需要多个域名、备用域名或独立状态管理，
  --    则继续保留独立的 operator_domain 表