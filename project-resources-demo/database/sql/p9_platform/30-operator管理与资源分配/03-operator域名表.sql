-- 文件用途:
-- 用于维护 operator 的访问域名。
-- 域名分为分站后台、代理后台和 H5 三种类型。
-- 同一个 operator 的同一种域名类型只能有一个启用中的域名。
-- 同一个启用中的域名不能同时绑定多个 operator。
BEGIN;
  CREATE TABLE PUBLIC.operator_domain (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 所属 operator 本地主键
    operator_id BIGINT NOT NULL,
    -- 域名
    -- 只保存域名本身，不包含协议、端口、路径和查询参数
    domain_name VARCHAR (253) NOT NULL,
    -- 域名类型: 1分站后台，2代理后台，3H5
    domain_type SMALLINT NOT NULL,
    -- 域名状态: 1启用，2停用
    status SMALLINT NOT NULL DEFAULT 1,
    -- 总网内部备注
    remark VARCHAR (1000),
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_operator_domain PRIMARY KEY (id),
    CONSTRAINT uk_operator_domain_operator_name UNIQUE (operator_id, domain_name),
    CONSTRAINT fk_operator_domain_operator FOREIGN KEY (operator_id) REFERENCES PUBLIC.OPERATOR (id)
  );

  -- 同一个启用中的域名不能同时绑定多个 operator
  CREATE UNIQUE INDEX uk_operator_domain_active_name ON PUBLIC.operator_domain (domain_name)
  WHERE
    status = 1;

  -- 同一个 operator 的同一种域名类型只能有一个启用中的域名
  CREATE UNIQUE INDEX uk_operator_domain_active_type ON PUBLIC.operator_domain (operator_id, domain_type)
  WHERE
    status = 1;

  -- 用于按 operator 和域名类型查询域名
  CREATE INDEX idx_operator_domain_operator_type ON PUBLIC.operator_domain (operator_id, domain_type);
  COMMENT ON TABLE PUBLIC.operator_domain IS '总网 operator 域名表';
  COMMENT ON COLUMN PUBLIC.operator_domain.id IS '主键ID';
  COMMENT ON COLUMN PUBLIC.operator_domain.operator_id IS '所属 operator 本地主键';
  COMMENT ON COLUMN PUBLIC.operator_domain.domain_name IS '域名';
  COMMENT ON COLUMN PUBLIC.operator_domain.domain_type IS '域名类型: 1分站后台，2代理后台，3H5';
  COMMENT ON COLUMN PUBLIC.operator_domain.status IS '域名状态: 1启用，2停用';
  COMMENT ON COLUMN PUBLIC.operator_domain.remark IS '总网内部备注';
  COMMENT ON COLUMN PUBLIC.operator_domain.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.operator_domain.updated_at IS '更新时间';
  COMMIT;