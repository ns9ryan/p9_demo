-- 文件用途:
-- 用于保存 operator 的公司资料、主要联系人和总网内部档案备注。
-- 每个 operator 只保存一份档案信息。
-- 草稿阶段允许档案信息不完整，完成创建时由业务代码校验必要信息。
BEGIN;
  CREATE TABLE PUBLIC.operator_profile (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 所属 operator 本地主键
    operator_id BIGINT NOT NULL,
    -- 公司名称
    company_name VARCHAR (200),
    -- 主要联系人名称
    contact_name VARCHAR (100),
    -- 主要联系人邮箱
    contact_email VARCHAR (255),
    -- 总网内部档案备注
    remark VARCHAR (1000),
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_operator_profile PRIMARY KEY (id),
    CONSTRAINT uk_operator_profile_operator UNIQUE (operator_id),
    CONSTRAINT fk_operator_profile_operator FOREIGN KEY (operator_id) REFERENCES PUBLIC.OPERATOR (id)
  );
  COMMENT ON TABLE PUBLIC.operator_profile IS '总网 operator 档案表';
  COMMENT ON COLUMN PUBLIC.operator_profile.id IS '主键ID';
  COMMENT ON COLUMN PUBLIC.operator_profile.operator_id IS '所属 operator 本地主键';
  COMMENT ON COLUMN PUBLIC.operator_profile.company_name IS '公司名称';
  COMMENT ON COLUMN PUBLIC.operator_profile.contact_name IS '主要联系人名称';
  COMMENT ON COLUMN PUBLIC.operator_profile.contact_email IS '主要联系人邮箱';
  COMMENT ON COLUMN PUBLIC.operator_profile.remark IS '总网内部档案备注';
  COMMENT ON COLUMN PUBLIC.operator_profile.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.operator_profile.updated_at IS '更新时间';
  COMMIT;