-- 文件用途：
-- 用于保存 operator 的公司资料、联系人、客服联系方式
-- 以及总网内部负责对接该 operator 的后台用户
-- 本表属于 operator 扩展档案，不保存 operator 核心运行字段
BEGIN;
  CREATE TABLE PUBLIC.operator_profile (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- operator ID
    -- 关联 operator.id
    operator_id BIGINT NOT NULL,
    -- 公司名称
    company_name VARCHAR (200),
    -- 主要联系人姓名
    contact_name VARCHAR (100),
    -- 主要联系人电话
    contact_phone VARCHAR (50),
    -- 主要联系人邮箱
    contact_email VARCHAR (200),
    -- 对外客服联系电话
    support_phone VARCHAR (50),
    -- 对外客服邮箱
    support_email VARCHAR (200),
    -- 总网负责对接该 operator 的后台用户ID
    -- 总网后台用户目前没有独立全局唯一码
    -- 逻辑关联 sys_user.id
    account_manager_user_id BIGINT,
    -- 总网内部档案备注
    remark VARCHAR (1000),
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_operator_profile PRIMARY KEY (id),
    CONSTRAINT uk_operator_profile_operator UNIQUE (operator_id),
    CONSTRAINT fk_operator_profile_operator FOREIGN KEY (operator_id) REFERENCES PUBLIC.OPERATOR (id),
    CONSTRAINT ck_operator_profile_company_name CHECK (company_name IS NULL OR BTRIM(company_name) <> ''),
    CONSTRAINT ck_operator_profile_contact_name CHECK (contact_name IS NULL OR BTRIM(contact_name) <> ''),
    CONSTRAINT ck_operator_profile_contact_phone CHECK (contact_phone IS NULL OR BTRIM(contact_phone) <> ''),
    CONSTRAINT ck_operator_profile_contact_email CHECK (contact_email IS NULL OR BTRIM(contact_email) <> ''),
    CONSTRAINT ck_operator_profile_support_phone CHECK (support_phone IS NULL OR BTRIM(support_phone) <> ''),
    CONSTRAINT ck_operator_profile_support_email CHECK (support_email IS NULL OR BTRIM(support_email) <> ''),
    CONSTRAINT ck_operator_profile_remark CHECK (remark IS NULL OR BTRIM(remark) <> '')
  );
  
  -- 用于按对接后台用户查询负责的 operator
  CREATE INDEX idx_operator_profile_account_manager ON PUBLIC.operator_profile (account_manager_user_id)
  WHERE
    account_manager_user_id IS NOT NULL;
  COMMENT ON TABLE PUBLIC.operator_profile IS '总网 operator 档案表';
  COMMENT ON COLUMN PUBLIC.operator_profile.id IS 'operator 档案本地主键';
  COMMENT ON COLUMN PUBLIC.operator_profile.operator_id IS 'operator ID，关联 operator.id';
  COMMENT ON COLUMN PUBLIC.operator_profile.company_name IS 'operator 所属公司名称';
  COMMENT ON COLUMN PUBLIC.operator_profile.contact_name IS 'operator 主要联系人姓名';
  COMMENT ON COLUMN PUBLIC.operator_profile.contact_phone IS 'operator 主要联系人电话';
  COMMENT ON COLUMN PUBLIC.operator_profile.contact_email IS 'operator 主要联系人邮箱';
  COMMENT ON COLUMN PUBLIC.operator_profile.support_phone IS 'operator 对外客服联系电话';
  COMMENT ON COLUMN PUBLIC.operator_profile.support_email IS 'operator 对外客服邮箱';
  COMMENT ON COLUMN PUBLIC.operator_profile.account_manager_user_id IS '总网负责对接该 operator 的后台用户ID，总网后台用户目前没有独立全局唯一码，逻辑关联 sys_user.id';
  COMMENT ON COLUMN PUBLIC.operator_profile.remark IS '总网内部档案备注';
  COMMENT ON COLUMN PUBLIC.operator_profile.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.operator_profile.updated_at IS '最后更新时间';
  COMMIT;
  
  -- 需要讨论的问题：
  -- 1. 当前 operator_profile 与 operator 位于同一个 p9_platform 数据库，
  --    因此 operator_id 通过本地ID关联 operator.id
  --    是否需要改为使用 operator_code 等稳定唯一标识关联
  --
  -- 2. 总网后台用户目前没有独立全局唯一码，
  --    account_manager_user_id 当前只能使用 sys_user.id 进行关联
  --    是否按此方案处理
  --
  -- 3. 厅后台修改客服邮箱或客服电话后，
  --    是否需要回传总网并同步更新本表
  --
  -- 4. 当前按照每个 operator 只保存一名主要联系人设计
  --    如果后续需要支持多个联系人，再增加独立的 operator 联系人表
  --
  -- 5. 第一版是否需要保存开版费、维护费和押金
  --    NS9 中这三个字段目前只用于展示，没有实际账单和支付业务
  --    如果 P9 也只用于展示，可以作为 operator 档案字段保存在本表
  --    如果后续需要缴费、退款、扣减、账单、支付状态或流水，
  --    再独立设计费用和账务相关明细表