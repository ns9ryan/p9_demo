-- 文件用途:
-- 用于维护总网向 operator 分配的经营地区。
-- 每个 operator 与同一个经营地区只保存一条分配关系。
-- 地区被回收后重新分配时继续更新原有记录。
-- 本表只保存总网分配状态，不保存厅本地启用状态。
BEGIN;
  CREATE TABLE PUBLIC.operator_region_allocation (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 所属 operator 本地主键
    operator_id BIGINT NOT NULL,
    -- 国家或地区唯一业务编码
    -- 逻辑关联 region.code
    region_code VARCHAR (2) NOT NULL,
    -- 分配状态: 1已分配，2已回收
    allocation_status SMALLINT NOT NULL DEFAULT 1,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_operator_region_allocation PRIMARY KEY (id),
    CONSTRAINT uk_operator_region_allocation UNIQUE (operator_id, region_code),
    CONSTRAINT fk_operator_region_allocation_operator FOREIGN KEY (operator_id) REFERENCES PUBLIC.OPERATOR (id)
  );
  COMMENT ON TABLE PUBLIC.operator_region_allocation IS '总网 operator 经营地区分配表';
  COMMENT ON COLUMN PUBLIC.operator_region_allocation.id IS '主键ID';
  COMMENT ON COLUMN PUBLIC.operator_region_allocation.operator_id IS '所属 operator 本地主键';
  COMMENT ON COLUMN PUBLIC.operator_region_allocation.region_code IS '国家或地区唯一业务编码';
  COMMENT ON COLUMN PUBLIC.operator_region_allocation.allocation_status IS '分配状态: 1已分配，2已回收';
  COMMENT ON COLUMN PUBLIC.operator_region_allocation.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.operator_region_allocation.updated_at IS '更新时间';
  COMMIT;