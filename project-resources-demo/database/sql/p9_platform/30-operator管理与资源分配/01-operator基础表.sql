-- 文件用途:
-- 用于维护总网创建和管理的 operator 基础信息。
-- 每个 operator 使用一个全局唯一业务编码。
-- operator 创建过程支持草稿、完成创建和异步发布。
-- 时区和结算货币在发布前允许修改，发布后不允许修改。
BEGIN;
  CREATE TABLE PUBLIC.OPERATOR (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- operator 全局唯一业务编码
    code VARCHAR (32) NOT NULL,
    -- operator 名称
    name VARCHAR (100) NOT NULL,
    -- operator 使用的 IANA 时区编码
    -- 逻辑关联 timezone.code
    timezone_code VARCHAR (64) NOT NULL,
    -- operator 使用的结算货币编码
    -- 逻辑关联 currency.code
    settlement_currency_code VARCHAR (16) NOT NULL,
    -- 创建状态: 1草稿，2已完成
    creation_status SMALLINT NOT NULL DEFAULT 1,
    -- 发布状态: 1未发布，2发布中，3已发布，4发布失败
    publish_status SMALLINT NOT NULL DEFAULT 1,
    -- 最近一次发布任务编号
    -- 用于关联调度中心发布任务和处理异步回调
    publish_task_no VARCHAR (64),
    -- 发布时间
    -- 调度中心回调发布成功后写入
    published_at TIMESTAMPTZ (3),
    -- operator 状态: 1正常，2暂停，3关闭
    status SMALLINT NOT NULL DEFAULT 1,
    -- 总网内部备注
    remark VARCHAR (1000),
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_operator PRIMARY KEY (id),
    CONSTRAINT uk_operator_code UNIQUE (code),
    CONSTRAINT uk_operator_publish_task_no UNIQUE (publish_task_no)
  );
  COMMENT ON TABLE PUBLIC.OPERATOR IS '总网 operator 基础表';
  COMMENT ON COLUMN PUBLIC.OPERATOR.id IS '主键ID';
  COMMENT ON COLUMN PUBLIC.OPERATOR.code IS 'operator 全局唯一业务编码';
  COMMENT ON COLUMN PUBLIC.OPERATOR.name IS 'operator 名称';
  COMMENT ON COLUMN PUBLIC.OPERATOR.timezone_code IS 'IANA 时区编码';
  COMMENT ON COLUMN PUBLIC.OPERATOR.settlement_currency_code IS '结算货币编码';
  COMMENT ON COLUMN PUBLIC.OPERATOR.creation_status IS '创建状态: 1草稿，2已完成';
  COMMENT ON COLUMN PUBLIC.OPERATOR.publish_status IS '发布状态: 1未发布，2发布中，3已发布，4发布失败';
  COMMENT ON COLUMN PUBLIC.OPERATOR.publish_task_no IS '最近一次发布任务编号';
  COMMENT ON COLUMN PUBLIC.OPERATOR.published_at IS '发布时间';
  COMMENT ON COLUMN PUBLIC.OPERATOR.status IS 'operator 状态: 1正常，2暂停，3关闭';
  COMMENT ON COLUMN PUBLIC.OPERATOR.remark IS '总网内部备注';
  COMMENT ON COLUMN PUBLIC.OPERATOR.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.OPERATOR.updated_at IS '更新时间';
  COMMIT;