-- 文件用途：
-- 用于维护总网创建和管理的 operator 基础信息
-- 每个 operator 使用一个全局唯一 operator_code
-- 当前按每个 operator 只使用一种时区和一种货币设计
-- 时区和货币在 operator 创建完成后原则上不允许修改
BEGIN;
  CREATE TABLE PUBLIC.OPERATOR (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- operator 全局唯一标识
    -- 用于跨数据库、跨服务、RPC、调度任务、日志和事件识别
    operator_code VARCHAR (32) NOT NULL,
    -- operator 名称
    -- 用于总网后台展示和识别
    operator_name VARCHAR (100) NOT NULL,
    -- operator 使用的时区ID
    -- 关联总网系统时区基础表 sys_timezone.id
    timezone_id BIGINT NOT NULL,
    -- operator 使用的货币ID
    -- 关联总网系统货币基础表 sys_currency.id
    currency_id BIGINT NOT NULL,
    -- operator 状态
    -- 1待开通
    -- 2正常
    -- 3暂停
    -- 4关闭
    status SMALLINT NOT NULL DEFAULT 1,
    -- 最近一次状态变更时间
    status_changed_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 最近一次状态变更原因
    status_reason VARCHAR (500),
    -- 创建记录的总网后台用户ID
    -- 逻辑关联 sys_user.id
    created_by BIGINT NOT NULL,
    -- 最后修改记录的总网后台用户ID
    -- 逻辑关联 sys_user.id
    updated_by BIGINT,
    -- 总网内部备注
    remark VARCHAR (1000),
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_operator PRIMARY KEY (id),
    CONSTRAINT uk_operator_code UNIQUE (operator_code),
    CONSTRAINT fk_operator_timezone FOREIGN KEY (timezone_id) REFERENCES PUBLIC.sys_timezone (id),
    CONSTRAINT fk_operator_currency FOREIGN KEY (currency_id) REFERENCES PUBLIC.sys_currency (id),
    CONSTRAINT ck_operator_code_not_blank CHECK (BTRIM(operator_code) <> ''),
    CONSTRAINT ck_operator_name_not_blank CHECK (BTRIM(operator_name) <> ''),
    CONSTRAINT ck_operator_status CHECK (status IN (1, 2, 3, 4)),
    CONSTRAINT ck_operator_status_reason CHECK (status_reason IS NULL OR BTRIM(status_reason) <> ''),
    CONSTRAINT ck_operator_remark CHECK (remark IS NULL OR BTRIM(remark) <> '')
  );
  COMMENT ON TABLE PUBLIC.OPERATOR IS '总网 operator 基础表';
  COMMENT ON COLUMN PUBLIC.OPERATOR.id IS 'operator 本地主键';
  COMMENT ON COLUMN PUBLIC.OPERATOR.operator_code IS 'operator 全局唯一标识，用于跨数据库、跨服务、RPC、调度任务、日志和事件识别';
  COMMENT ON COLUMN PUBLIC.OPERATOR.operator_name IS 'operator 名称，用于总网后台展示和识别';
  COMMENT ON COLUMN PUBLIC.OPERATOR.timezone_id IS 'operator 使用的时区ID，关联 sys_timezone.id';
  COMMENT ON COLUMN PUBLIC.OPERATOR.currency_id IS 'operator 使用的货币ID，关联 sys_currency.id';
  COMMENT ON COLUMN PUBLIC.OPERATOR.status IS 'operator 状态：1待开通，2正常，3暂停，4关闭';
  COMMENT ON COLUMN PUBLIC.OPERATOR.status_changed_at IS '最近一次状态变更时间';
  COMMENT ON COLUMN PUBLIC.OPERATOR.status_reason IS '最近一次状态变更原因';
  COMMENT ON COLUMN PUBLIC.OPERATOR.created_by IS '创建记录的总网后台用户ID，逻辑关联 sys_user.id';
  COMMENT ON COLUMN PUBLIC.OPERATOR.updated_by IS '最后修改记录的总网后台用户ID，逻辑关联 sys_user.id';
  COMMENT ON COLUMN PUBLIC.OPERATOR.remark IS '总网内部备注';
  COMMENT ON COLUMN PUBLIC.OPERATOR.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.OPERATOR.updated_at IS '最后更新时间';
  COMMIT;
  
  -- 需要讨论的问题：
  -- 1. operator_code 的具体生成规则和长度，
  --    等开始开发并确定编码生成方式时再确认，
  --    当前字段暂按 VARCHAR(32) 设计
  --
  -- 2. 是否可以确认每个 operator 永远只使用一种货币，
  --    不会出现会员钱包货币、充值支持货币、游戏货币、
  --    页面展示货币等多币种业务
  --    当前按照每个 operator 只有一种货币且创建后不能修改设计
  --    如果后续需要支持多币种，需要重新设计货币配置、
  --    钱包、充值、游戏、账务和结算等相关表结构，
  --    涉及范围较大，后期调整的开发和数据迁移工作量会比较大，
  --    建议在项目开始开发前明确是否需要支持多币种
  --
  -- 3. 是否可以确认每个 operator 永远只使用一个时区，
  --    并且创建完成后不能修改
  --    当前统计周期、财务日、报表和业务时间范围都会依赖该时区
  --    如果后续允许修改时区，需要重新处理历史数据、
  --    统计边界、结算周期和时间转换规则，
  --    涉及范围较大，后期调整的开发和数据修正工作量会比较大，
  --    建议在项目开始开发前明确时区是否固定且不可修改
  --
  -- 4. 当前 timezone_id 和 currency_id 通过本地ID关联
  --    p9_platform 中的 sys_timezone.id 和 sys_currency.id
  --    是否需要改为直接保存稳定唯一标识
  --    timezone_code 和 currency_code
  --
  -- 5. operator 进入暂停或关闭状态后，
  --    是否禁止厅后台、代理后台和会员端登录，
  --    是否禁止新增业务，以及是否允许继续完成历史业务结算