-- 文件用途：
-- 用于维护总网向各 operator 分配的系统语言
-- 本表只记录总网分配状态，不保存厅本地启用状态和当前默认语言
-- 系统语言完整主数据由 sys_language 统一维护
BEGIN;
  CREATE TABLE PUBLIC.operator_language_allocation (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- operator ID，关联 operator.id
    operator_id BIGINT NOT NULL,
    -- 系统语言ID，关联 sys_language.id
    language_id BIGINT NOT NULL,
    -- 总网分配状态
    -- 1已分配
    -- 2已收回
    allocation_status SMALLINT NOT NULL DEFAULT 1,
    -- 最近一次分配时间
    -- 重新分配时更新本字段
    allocated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 最近一次收回时间
    -- 当前处于已分配状态时为NULL
    revoked_at TIMESTAMPTZ (3),
    -- 最近一次收回原因
    -- 当前处于已分配状态时为NULL
    revoke_reason VARCHAR (500),
    -- 首次创建分配记录的总网后台用户ID
    -- 逻辑关联 admin_user.id
    created_by BIGINT NOT NULL,
    -- 最后修改分配状态的总网后台用户ID
    -- 逻辑关联 admin_user.id
    updated_by BIGINT,
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_operator_language_allocation PRIMARY KEY (id),
    CONSTRAINT uk_operator_language_allocation UNIQUE (operator_id, language_id),
    CONSTRAINT fk_operator_language_allocation_operator FOREIGN KEY (operator_id) REFERENCES PUBLIC.OPERATOR (id),
    CONSTRAINT fk_operator_language_allocation_language FOREIGN KEY (language_id) REFERENCES PUBLIC.sys_language (id),
    CONSTRAINT ck_operator_language_allocation_status CHECK (allocation_status IN (1, 2)),
    CONSTRAINT ck_operator_language_allocation_revoke_reason CHECK (revoke_reason IS NULL OR BTRIM(revoke_reason) <> ''),
    CONSTRAINT ck_operator_language_allocation_revoke_state CHECK ((allocation_status = 1 AND revoked_at IS NULL AND revoke_reason IS NULL) OR (allocation_status = 2 AND revoked_at IS NOT NULL)),
    CONSTRAINT ck_operator_language_allocation_time CHECK (revoked_at IS NULL OR revoked_at >= allocated_at)
  );
  COMMENT ON TABLE PUBLIC.operator_language_allocation IS '总网 operator 系统语言分配表';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.id IS 'operator 语言分配记录本地主键';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.operator_id IS 'operator ID，关联 operator.id';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.language_id IS '系统语言ID，关联 sys_language.id';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.allocation_status IS '总网分配状态：1已分配，2已收回';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.allocated_at IS '最近一次分配时间，重新分配时更新';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.revoked_at IS '最近一次收回时间，当前已分配时为NULL';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.revoke_reason IS '最近一次收回原因，当前已分配时为NULL';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.created_by IS '首次创建分配记录的总网后台用户ID，逻辑关联 admin_user.id';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.updated_by IS '最后修改分配状态的总网后台用户ID，逻辑关联 admin_user.id';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.updated_at IS '最后更新时间';
  COMMIT;
  
  -- 需要讨论的问题：
  -- 1. 当前设计不在本表保存默认语言
  --    开通时选择的初始默认语言准备保存在 operator_provisioning，
  --    厅当前默认语言保存在 p9_operator，是否按此方案处理
  --
  -- 2. 总网是否需要支持收回和重新分配 operator 已分配的语言
  --    如果不需要，则删除 allocation_status、revoked_at 和 revoke_reason，
  --    每条记录只表示当前已分配语言，下面第3、4点也不需要讨论
  --
  -- 3. 如果保留语言收回功能，总网收回 operator 当前默认语言时，
  --    是要求厅先切换默认语言，还是由系统自动切换到其他可用语言
  --
  -- 4. 如果保留语言重新分配功能，重新分配已收回的语言后，
  --    是否保持厅本地停用状态，由厅管理员重新启用