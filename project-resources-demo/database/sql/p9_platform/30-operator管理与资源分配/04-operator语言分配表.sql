-- 文件用途:
-- 用于维护总网向 operator 分配的系统语言。
-- 每个 operator 与同一种语言只保存一条分配关系。
-- 语言被回收后重新分配时继续更新原有记录。
-- 本表只保存总网分配状态，不保存厅本地启用状态和默认语言。
BEGIN;
  CREATE TABLE PUBLIC.operator_language_allocation (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 所属 operator 本地主键
    operator_id BIGINT NOT NULL,
    -- 系统语言唯一业务编码
    -- 逻辑关联 language.code
    language_code VARCHAR (35) NOT NULL,
    -- 分配状态: 1已分配，2已回收
    allocation_status SMALLINT NOT NULL DEFAULT 1,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_operator_language_allocation PRIMARY KEY (id),
    CONSTRAINT uk_operator_language_allocation UNIQUE (operator_id, language_code),
    CONSTRAINT fk_operator_language_allocation_operator FOREIGN KEY (operator_id) REFERENCES PUBLIC.OPERATOR (id)
  );
  COMMENT ON TABLE PUBLIC.operator_language_allocation IS '总网 operator 语言分配表';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.id IS '主键ID';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.operator_id IS '所属 operator 本地主键';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.language_code IS '系统语言唯一业务编码';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.allocation_status IS '分配状态: 1已分配，2已回收';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.operator_language_allocation.updated_at IS '更新时间';
  COMMIT;