-- 文件用途:
-- 用于维护总网向 operator 分配的代理子线路。
-- 每个 operator 与同一个代理子线路只保存一条分配关系。
-- 子线路被回收后重新分配时继续更新原有记录。
-- 代理模式和代理子线路由代码常量定义，本表只保存代理子线路编码和总网分配状态。
-- 本表不保存厅本地启用状态。
-- agent_line 只属于分层代理体系，不包含 affiliate。
BEGIN;
  CREATE TABLE PUBLIC.operator_agent_line_allocation (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 所属 operator 本地主键
    operator_id BIGINT NOT NULL,
    -- 代理子线路编码
    -- 对应代码中定义的稳定线路常量，例如 CASH_TOP、CASH_TRIAL、CASH_TEST、CREDIT_TOP
    agent_line_code VARCHAR (32) NOT NULL,
    -- 分配状态: 1已分配，2已回收
    allocation_status SMALLINT NOT NULL DEFAULT 1,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_operator_agent_line_allocation PRIMARY KEY (id),
    CONSTRAINT uk_operator_agent_line_allocation UNIQUE (operator_id, agent_line_code),
    CONSTRAINT fk_operator_agent_line_allocation_operator FOREIGN KEY (operator_id) REFERENCES PUBLIC.OPERATOR (id)
  );
  COMMENT ON TABLE PUBLIC.operator_agent_line_allocation IS '总网 operator 代理子线路分配表';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.id IS '主键ID';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.operator_id IS '所属 operator 本地主键';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.agent_line_code IS '代理子线路编码';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.allocation_status IS '分配状态: 1已分配，2已回收';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.updated_at IS '更新时间';
  COMMIT;