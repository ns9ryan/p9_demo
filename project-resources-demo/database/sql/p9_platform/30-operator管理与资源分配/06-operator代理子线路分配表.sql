-- 文件用途：
-- 用于维护总网向各 operator 分配的代理子线路。
-- 代理模式和代理子线路由代码常量定义，本表只保存代理子线路编码和总网分配状态。
-- 本表不保存厅本地启用状态。
-- agent_line 只属于分层代理体系，不包含 affiliate。
BEGIN;
  CREATE TABLE PUBLIC.operator_agent_line_allocation (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- operator ID，关联 operator.id。
    operator_id BIGINT NOT NULL,
    -- 代理子线路编码，对应代码中定义的稳定线路常量。
    -- 例如：CASH_TOP、CASH_TRIAL、CASH_TEST、CREDIT_TOP。
    -- 代理模式由代码根据本字段映射，不在本表重复保存代理模式编码。
    agent_line_code VARCHAR (64) NOT NULL,
    -- 总网分配状态：
    -- 1：已分配；
    -- 2：已收回。
    allocation_status SMALLINT NOT NULL DEFAULT 1,
    -- 最近一次分配时间。
    -- 首次分配时写入，重新分配时更新。
    allocated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 最近一次收回时间。
    -- 当前处于已分配状态时必须为 NULL。
    revoked_at TIMESTAMPTZ (3),
    -- 最近一次收回原因。
    -- 当前处于已分配状态时必须为 NULL。
    revoke_reason VARCHAR (500),
    -- 首次创建分配记录的总网后台用户 ID。
    -- 逻辑关联 admin_user.id。
    created_by BIGINT NOT NULL,
    -- 最后修改分配状态的总网后台用户 ID。
    -- 逻辑关联 admin_user.id。
    updated_by BIGINT,
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_operator_agent_line_allocation PRIMARY KEY (id),
    CONSTRAINT uk_operator_agent_line_allocation UNIQUE (operator_id, agent_line_code),
    CONSTRAINT fk_operator_agent_line_allocation_operator FOREIGN KEY (operator_id) REFERENCES PUBLIC.OPERATOR (id),
    CONSTRAINT ck_operator_agent_line_allocation_code CHECK (BTRIM(agent_line_code) <> '' AND agent_line_code = BTRIM(agent_line_code)),
    CONSTRAINT ck_operator_agent_line_allocation_status CHECK (allocation_status IN (1, 2)),
    CONSTRAINT ck_operator_agent_line_allocation_revoke_reason CHECK (revoke_reason IS NULL OR BTRIM(revoke_reason) <> ''),
    CONSTRAINT ck_operator_agent_line_allocation_revoke_state CHECK ((allocation_status = 1 AND revoked_at IS NULL AND revoke_reason IS NULL) OR (allocation_status = 2 AND revoked_at IS NOT NULL)),
    CONSTRAINT ck_operator_agent_line_allocation_time CHECK (revoked_at IS NULL OR revoked_at >= allocated_at)
  );
  COMMENT ON TABLE PUBLIC.operator_agent_line_allocation IS 'operator 代理子线路分配表';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.id IS '分配记录主键';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.operator_id IS 'operator ID';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.agent_line_code IS '代理子线路编码';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.allocation_status IS '分配状态：1已分配，2已收回';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.allocated_at IS '最近分配时间';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.revoked_at IS '最近收回时间';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.revoke_reason IS '最近收回原因';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.created_by IS '创建用户 ID';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.updated_by IS '最后修改用户 ID';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.operator_agent_line_allocation.updated_at IS '最后更新时间';
  COMMIT;
  
  -- 需要讨论的问题：
  -- 1. 总网是否需要支持收回 operator 已分配的代理子线路。
  --    如果首版不需要收回功能，可以删除 allocation_status、revoked_at 和 revoke_reason，
  --    每条记录只表示当前已分配的代理子线路；取消分配时直接物理删除记录。
  --
  -- 2. 如果保留代理子线路收回功能，需要明确已经存在 agent、member、
  --    未结算注单或未完成结算业务时是否允许收回。
  --
  -- 3. agent_line_code 的合法值由代码常量校验。
  --    数据库不保存代理子线路基础表，也不对代码常量建立外键。