-- 文件用途:
-- 用于维护 P9 平台支持的国家和地区基础数据。
-- 国家或地区编码作为全局唯一业务编码。
-- 中国大陆不属于 P9 支持的经营地区。
BEGIN;
  CREATE TABLE PUBLIC.region (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- ISO 3166-1 Alpha-2 国家或地区全局唯一业务编码，例如 JP
    code VARCHAR (2) NOT NULL,
    -- 国际电话区号，不包含加号
    calling_code VARCHAR (4),
    -- 国家或地区的多语言名称
    name_i18n JSONB NOT NULL,
    -- 状态: 1启用，2停用
    status SMALLINT NOT NULL DEFAULT 1,
    -- 排序值，数值越小越靠前
    sort_no INTEGER NOT NULL DEFAULT 0,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_region PRIMARY KEY (id),
    CONSTRAINT uk_region_code UNIQUE (code)
  );
  COMMENT ON TABLE PUBLIC.region IS '系统国家地区表';
  COMMENT ON COLUMN PUBLIC.region.id IS '主键ID';
  COMMENT ON COLUMN PUBLIC.region.code IS '国家或地区编码';
  COMMENT ON COLUMN PUBLIC.region.calling_code IS '国际电话区号，不包含加号';
  COMMENT ON COLUMN PUBLIC.region.name_i18n IS '多语言名称';
  COMMENT ON COLUMN PUBLIC.region.status IS '状态: 1启用，2停用';
  COMMENT ON COLUMN PUBLIC.region.sort_no IS '排序值，数值越小越靠前';
  COMMENT ON COLUMN PUBLIC.region.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.region.updated_at IS '更新时间';
