-- 文件用途:
-- 用于维护 P9 平台支持的系统时区基础数据。
-- 时区编码作为全局唯一业务编码，供其他业务数据引用。
BEGIN;
  CREATE TABLE PUBLIC.timezone (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- IANA 时区全局唯一业务编码，例如 Asia/Tokyo
    code VARCHAR (64) NOT NULL,
    -- 时区的多语言名称
    name_i18n JSONB NOT NULL,
    -- 状态: 1启用，2停用
    status SMALLINT NOT NULL DEFAULT 1,
    -- 排序值，数值越小越靠前
    sort_no INTEGER NOT NULL DEFAULT 0,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_timezone PRIMARY KEY (id),
    CONSTRAINT uk_timezone_code UNIQUE (code)
  );
  COMMENT ON TABLE PUBLIC.timezone IS '系统时区表';
  COMMENT ON COLUMN PUBLIC.timezone.id IS '主键ID';
