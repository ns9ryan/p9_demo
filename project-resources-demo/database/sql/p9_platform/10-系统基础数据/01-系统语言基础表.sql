-- 文件用途:
-- 用于维护 P9 平台支持的系统语言基础数据。
-- 语言编码作为全局唯一业务编码，供其他业务数据引用。
BEGIN;
  CREATE TABLE PUBLIC.LANGUAGE (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 语言全局唯一业务编码，例如 zh-CN
    code VARCHAR (20) NOT NULL,
    -- 语言的多语言名称
    name_i18n JSONB NOT NULL,
    -- 状态: 1启用，2停用
    status SMALLINT NOT NULL DEFAULT 1,
    -- 排序值，数值越小越靠前
    sort_no INTEGER NOT NULL DEFAULT 0,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_language PRIMARY KEY (id),
    CONSTRAINT uk_language_code UNIQUE (code)
  );
  COMMENT ON TABLE PUBLIC.LANGUAGE IS '系统语言表';
  COMMENT ON COLUMN PUBLIC.LANGUAGE.id IS '主键ID';
  COMMENT ON COLUMN PUBLIC.LANGUAGE.code IS '语言编码';
  COMMENT ON COLUMN PUBLIC.LANGUAGE.name_i18n IS '多语言名称';
  COMMENT ON COLUMN PUBLIC.LANGUAGE.status IS '状态: 1启用，2停用';
  COMMENT ON COLUMN PUBLIC.LANGUAGE.sort_no IS '排序值，数值越小越靠前';
  COMMENT ON COLUMN PUBLIC.LANGUAGE.created_at IS '创建时间';
