-- 文件用途：
-- 用于维护总网后台角色与菜单权限资源的关联关系。
-- 一个角色可以关联多个目录、菜单和按钮权限资源。
BEGIN;
  CREATE TABLE PUBLIC.sys_role_menu (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 后台角色ID
    role_id BIGINT NOT NULL,
    -- 菜单权限资源ID
    menu_id BIGINT NOT NULL,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sys_role_menu PRIMARY KEY (id),
    CONSTRAINT fk_sys_role_menu_role FOREIGN KEY (role_id) REFERENCES PUBLIC.sys_role (id) ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT fk_sys_role_menu_menu FOREIGN KEY (menu_id) REFERENCES PUBLIC.sys_menu (id) ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT uk_sys_role_menu_role_menu UNIQUE (role_id, menu_id)
  );

  -- 用于按菜单权限资源查询关联角色
  CREATE INDEX idx_sys_role_menu_menu_role ON PUBLIC.sys_role_menu (menu_id, role_id);
  COMMENT ON TABLE PUBLIC.sys_role_menu IS '总网后台角色菜单关联表';
  COMMENT ON COLUMN PUBLIC.sys_role_menu.id IS '角色菜单关系本地主键';
  COMMENT ON COLUMN PUBLIC.sys_role_menu.role_id IS '后台角色ID';
  COMMENT ON COLUMN PUBLIC.sys_role_menu.menu_id IS '菜单权限资源ID';
  COMMENT ON COLUMN PUBLIC.sys_role_menu.created_at IS '创建时间';
  COMMIT;