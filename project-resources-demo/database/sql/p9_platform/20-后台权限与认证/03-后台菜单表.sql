-- 文件用途：
-- 用于维护总网后台的目录、菜单和按钮权限资源。
-- 菜单数据由系统初始化和版本升级统一维护。
BEGIN;
  CREATE TABLE PUBLIC.sys_menu (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 上级菜单ID，顶级目录为空
    parent_id BIGINT,
    -- 资源类型：1目录，2菜单，3按钮
    menu_type SMALLINT NOT NULL,
    -- 资源编码
    resource_code VARCHAR (150) NOT NULL,
    -- 资源名称
    menu_name VARCHAR (100) NOT NULL,
    -- 资源状态：1启用，2停用
    status SMALLINT NOT NULL DEFAULT 1,
    -- 展示顺序，数值越小越靠前
    sort_no INTEGER NOT NULL DEFAULT 0,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sys_menu PRIMARY KEY (id),
    CONSTRAINT fk_sys_menu_parent FOREIGN KEY (parent_id) REFERENCES PUBLIC.sys_menu (id) ON UPDATE RESTRICT ON DELETE RESTRICT
  );

  -- 资源编码不区分大小写唯一
  CREATE UNIQUE INDEX uk_sys_menu_resource_code ON PUBLIC.sys_menu (LOWER(resource_code));

  -- 用于查询菜单树
  CREATE INDEX idx_sys_menu_parent_sort ON PUBLIC.sys_menu (parent_id, status, sort_no, id);
  COMMENT ON TABLE PUBLIC.sys_menu IS '总网后台菜单表';
  COMMENT ON COLUMN PUBLIC.sys_menu.id IS '菜单资源本地主键';
  COMMENT ON COLUMN PUBLIC.sys_menu.parent_id IS '上级菜单ID，顶级目录为空';
  COMMENT ON COLUMN PUBLIC.sys_menu.menu_type IS '资源类型：1目录，2菜单，3按钮';
  COMMENT ON COLUMN PUBLIC.sys_menu.resource_code IS '资源编码';
  COMMENT ON COLUMN PUBLIC.sys_menu.menu_name IS '资源名称';
  COMMENT ON COLUMN PUBLIC.sys_menu.status IS '资源状态：1启用，2停用';
  COMMENT ON COLUMN PUBLIC.sys_menu.sort_no IS '展示顺序，数值越小越靠前';
  COMMENT ON COLUMN PUBLIC.sys_menu.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.sys_menu.updated_at IS '更新时间';
  COMMIT;