-- 文件用途：
-- 用于保存总网后台允许登录的 IP 地址和 CIDR 网段。
-- 是否启用白名单由后台登录安全配置控制。
BEGIN;
  CREATE TABLE PUBLIC.sys_login_ip_whitelist (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 允许登录的IP地址或CIDR网段
    ip_cidr CIDR NOT NULL,
    -- 备注
    remark VARCHAR (255),
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sys_login_ip_whitelist PRIMARY KEY (id),
    CONSTRAINT uk_sys_login_ip_whitelist_ip_cidr UNIQUE (ip_cidr)
  );
  COMMENT ON TABLE PUBLIC.sys_login_ip_whitelist IS '总网后台登录IP白名单表';
  COMMENT ON COLUMN PUBLIC.sys_login_ip_whitelist.id IS 'IP白名单本地主键';
  COMMENT ON COLUMN PUBLIC.sys_login_ip_whitelist.ip_cidr IS '允许登录的IP地址或CIDR网段';
  COMMENT ON COLUMN PUBLIC.sys_login_ip_whitelist.remark IS '备注';
  COMMENT ON COLUMN PUBLIC.sys_login_ip_whitelist.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.sys_login_ip_whitelist.updated_at IS '更新时间';
  COMMIT;