-- 文件用途：
-- 用于保存总网后台用户的 TOTP 绑定信息。
-- 一个后台用户最多绑定一个 TOTP 验证器。
BEGIN;
  CREATE TABLE PUBLIC.sys_user_totp (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 后台用户ID
    user_id BIGINT NOT NULL,
    -- 加密后的TOTP密钥
    secret_ciphertext VARCHAR (512) NOT NULL,
    -- 绑定时间
    bound_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sys_user_totp PRIMARY KEY (id),
    CONSTRAINT fk_sys_user_totp_user FOREIGN KEY (user_id) REFERENCES PUBLIC.sys_user (id) ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT uk_sys_user_totp_user UNIQUE (user_id)
  );
  COMMENT ON TABLE PUBLIC.sys_user_totp IS '总网后台用户TOTP绑定表';
  COMMENT ON COLUMN PUBLIC.sys_user_totp.id IS 'TOTP绑定记录本地主键';
  COMMENT ON COLUMN PUBLIC.sys_user_totp.user_id IS '后台用户ID';
  COMMENT ON COLUMN PUBLIC.sys_user_totp.secret_ciphertext IS '加密后的TOTP密钥';
  COMMENT ON COLUMN PUBLIC.sys_user_totp.bound_at IS '绑定时间';
  COMMENT ON COLUMN PUBLIC.sys_user_totp.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.sys_user_totp.updated_at IS '更新时间';
  COMMIT;