-- 文件用途：
-- 用于维护总网后台用户与角色的关联关系。
-- 一个用户可以绑定多个角色，一个角色也可以绑定多个用户。
BEGIN;
  CREATE TABLE PUBLIC.sys_user_role (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 后台用户ID
    user_id BIGINT NOT NULL,
    -- 后台角色ID
    role_id BIGINT NOT NULL,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sys_user_role PRIMARY KEY (id),
    CONSTRAINT fk_sys_user_role_user FOREIGN KEY (user_id) REFERENCES PUBLIC.sys_user (id) ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT fk_sys_user_role_role FOREIGN KEY (role_id) REFERENCES PUBLIC.sys_role (id) ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT uk_sys_user_role_user_role UNIQUE (user_id, role_id)
  );

  -- 用于按角色查询关联用户
  CREATE INDEX idx_sys_user_role_role_user ON PUBLIC.sys_user_role (role_id, user_id);
  COMMENT ON TABLE PUBLIC.sys_user_role IS '总网后台用户角色关联表';
  COMMENT ON COLUMN PUBLIC.sys_user_role.id IS '用户角色关系本地主键';
  COMMENT ON COLUMN PUBLIC.sys_user_role.user_id IS '后台用户ID';
  COMMENT ON COLUMN PUBLIC.sys_user_role.role_id IS '后台角色ID';
  COMMENT ON COLUMN PUBLIC.sys_user_role.created_at IS '创建时间';
  COMMIT;