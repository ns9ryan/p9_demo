-- 文件用途：
-- 用于记录总网后台管理员的重要操作及其请求和响应信息。
BEGIN;
  CREATE TABLE PUBLIC.sys_admin_action_log (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 操作用户ID
    user_id BIGINT NOT NULL,
    -- 所属 operator 的本地主键，总网操作为空
    operator_id BIGINT,
    -- HTTP请求方法
    request_method VARCHAR (10) NOT NULL,
    -- API请求路径
    request_path VARCHAR (500) NOT NULL,
    -- URL查询参数
    request_query TEXT,
    -- 脱敏后的请求内容
    request_body TEXT,
    -- 操作结果：1成功，2失败
    action_result SMALLINT NOT NULL,
    -- HTTP响应状态码
    response_status INTEGER NOT NULL,
    -- 脱敏后的响应内容
    response_body TEXT,
    -- 请求耗时，单位毫秒
    duration_ms INTEGER NOT NULL DEFAULT 0,
    -- 操作IP
    client_ip INET NOT NULL,
    -- 浏览器和设备标识
    user_agent VARCHAR (1000),
    -- 操作时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sys_admin_action_log PRIMARY KEY (id),
    CONSTRAINT fk_sys_admin_action_log_user FOREIGN KEY (user_id) REFERENCES PUBLIC.sys_user (id) ON UPDATE RESTRICT ON DELETE RESTRICT
  );

  -- 用于按时间查询操作日志
  CREATE INDEX idx_sys_admin_action_log_time ON PUBLIC.sys_admin_action_log (created_at DESC);

  -- 用于查询指定管理员的操作日志
  CREATE INDEX idx_sys_admin_action_log_user_time ON PUBLIC.sys_admin_action_log (user_id, created_at DESC);

  -- 用于查询指定API的操作日志
  CREATE INDEX idx_sys_admin_action_log_api_time ON PUBLIC.sys_admin_action_log (request_method, request_path, created_at DESC);

  -- 用于按厅和时间查询操作日志
  CREATE INDEX idx_sys_admin_action_log_operator_time ON PUBLIC.sys_admin_action_log (operator_id, created_at DESC);
  COMMENT ON TABLE PUBLIC.sys_admin_action_log IS '总网后台管理员操作日志表';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.id IS '操作日志本地主键';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.user_id IS '操作用户ID';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.operator_id IS '所属operator的本地主键，总网操作为空';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.request_method IS 'HTTP请求方法';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.request_path IS 'API请求路径';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.request_query IS 'URL查询参数';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.request_body IS '脱敏后的请求内容';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.action_result IS '操作结果：1成功，2失败';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.response_status IS 'HTTP响应状态码';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.response_body IS '脱敏后的响应内容';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.duration_ms IS '请求耗时，单位毫秒';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.client_ip IS '操作IP';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.user_agent IS '浏览器和设备标识';
  COMMENT ON COLUMN PUBLIC.sys_admin_action_log.created_at IS '操作时间';
  COMMIT;