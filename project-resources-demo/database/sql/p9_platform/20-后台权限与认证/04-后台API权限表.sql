-- 文件用途：
-- 用于维护总网后台需要进行 Casbin 鉴权的 API 权限定义。
-- API 数据由系统初始化和版本升级统一维护。
BEGIN;
  CREATE TABLE PUBLIC.sys_api (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 微服务分组
    service_name VARCHAR (100) NOT NULL,
    -- HTTP请求方法
    METHOD VARCHAR (10) NOT NULL,
    -- API请求路径
    PATH VARCHAR (255) NOT NULL,
    -- API描述
    description VARCHAR (255),
    -- 是否为必要API
    is_required BOOLEAN NOT NULL DEFAULT FALSE,
    -- API状态：1启用，2停用
    status SMALLINT NOT NULL DEFAULT 1,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sys_api PRIMARY KEY (id)
  );

  -- 同一个请求方法和请求路径只能对应一个API权限
  CREATE UNIQUE INDEX uk_sys_api_method_path ON PUBLIC.sys_api (METHOD, PATH);

  -- 用于按微服务分组查询API权限
  CREATE INDEX idx_sys_api_service ON PUBLIC.sys_api (service_name, status, id);
  COMMENT ON TABLE PUBLIC.sys_api IS '总网后台API权限表';
  COMMENT ON COLUMN PUBLIC.sys_api.id IS 'API权限本地主键';
  COMMENT ON COLUMN PUBLIC.sys_api.service_name IS '微服务分组';
  COMMENT ON COLUMN PUBLIC.sys_api.METHOD IS 'HTTP请求方法';
  COMMENT ON COLUMN PUBLIC.sys_api.PATH IS 'API请求路径';
  COMMENT ON COLUMN PUBLIC.sys_api.description IS 'API描述';
  COMMENT ON COLUMN PUBLIC.sys_api.is_required IS '是否为必要API';
  COMMENT ON COLUMN PUBLIC.sys_api.status IS 'API状态：1启用，2停用';
  COMMENT ON COLUMN PUBLIC.sys_api.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.sys_api.updated_at IS '更新时间';
  COMMIT;