-- 文件用途：
-- 用于保存总网后台用户。
-- 用户可以绑定多个角色，删除用户时采用软删除方式保留历史记录。
BEGIN;
  CREATE TABLE PUBLIC.sys_user (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 登录用户名
    username VARCHAR (64) NOT NULL,
    -- 登录密码哈希
    password_hash VARCHAR (255) NOT NULL,
    -- 后台显示名称
    display_name VARCHAR (100) NOT NULL,
    -- 手机号
    mobile VARCHAR (32),
    -- 邮箱
    email VARCHAR (255),
    -- 用户状态：1正常，2停用
    status SMALLINT NOT NULL DEFAULT 1,
    -- 是否为总网超级管理员
    is_super_admin BOOLEAN NOT NULL DEFAULT FALSE,
    -- 最近登录时间
    last_login_at TIMESTAMPTZ (3),
    -- 最近登录IP
    last_login_ip INET,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 软删除时间
    deleted_at TIMESTAMPTZ (3),
    CONSTRAINT pk_sys_user PRIMARY KEY (id)
  );

  -- 总网后台用户名不区分大小写唯一
  -- 已删除用户的用户名不允许重新使用
  CREATE UNIQUE INDEX uk_sys_user_username ON PUBLIC.sys_user (LOWER(username));
  COMMENT ON TABLE PUBLIC.sys_user IS '总网后台用户表';
  COMMENT ON COLUMN PUBLIC.sys_user.id IS '后台用户本地主键';
  COMMENT ON COLUMN PUBLIC.sys_user.username IS '登录用户名';
  COMMENT ON COLUMN PUBLIC.sys_user.password_hash IS '登录密码哈希';
  COMMENT ON COLUMN PUBLIC.sys_user.display_name IS '后台显示名称';
  COMMENT ON COLUMN PUBLIC.sys_user.mobile IS '手机号';
  COMMENT ON COLUMN PUBLIC.sys_user.email IS '邮箱';
  COMMENT ON COLUMN PUBLIC.sys_user.status IS '用户状态：1正常，2停用';
  COMMENT ON COLUMN PUBLIC.sys_user.is_super_admin IS '是否为总网超级管理员';
  COMMENT ON COLUMN PUBLIC.sys_user.last_login_at IS '最近登录时间';
  COMMENT ON COLUMN PUBLIC.sys_user.last_login_ip IS '最近登录IP';
  COMMENT ON COLUMN PUBLIC.sys_user.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.sys_user.updated_at IS '更新时间';
  COMMENT ON COLUMN PUBLIC.sys_user.deleted_at IS '软删除时间';
  COMMIT;