-- 文件用途：
-- 用于保存总网后台角色的 Casbin API 权限规则。
-- 本表只保存角色与 API 的 p 策略。
BEGIN;
  CREATE TABLE PUBLIC.casbin_rule (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- Casbin策略类型，当前固定为p
    ptype VARCHAR (16) NOT NULL DEFAULT 'p',
    -- 角色编码
    v0 VARCHAR (255) NOT NULL DEFAULT '',
    -- API请求路径
    v1 VARCHAR (255) NOT NULL DEFAULT '',
    -- HTTP请求方法
    v2 VARCHAR (255) NOT NULL DEFAULT '',
    -- 当前未使用
    v3 VARCHAR (255) NOT NULL DEFAULT '',
    -- 当前未使用
    v4 VARCHAR (255) NOT NULL DEFAULT '',
    -- 当前未使用
    v5 VARCHAR (255) NOT NULL DEFAULT '',
    CONSTRAINT pk_casbin_rule PRIMARY KEY (id)
  );

  -- 同一角色不能重复配置相同的API权限
  CREATE UNIQUE INDEX uk_casbin_rule_policy ON PUBLIC.casbin_rule (ptype, v0, v1, v2, v3, v4, v5);
  COMMENT ON TABLE PUBLIC.casbin_rule IS '总网后台Casbin权限规则表';
  COMMENT ON COLUMN PUBLIC.casbin_rule.id IS 'Casbin规则本地主键';
  COMMENT ON COLUMN PUBLIC.casbin_rule.ptype IS 'Casbin策略类型，当前固定为p';
  COMMENT ON COLUMN PUBLIC.casbin_rule.v0 IS '角色编码';
  COMMENT ON COLUMN PUBLIC.casbin_rule.v1 IS 'API请求路径';
  COMMENT ON COLUMN PUBLIC.casbin_rule.v2 IS 'HTTP请求方法';
  COMMENT ON COLUMN PUBLIC.casbin_rule.v3 IS '当前未使用';
  COMMENT ON COLUMN PUBLIC.casbin_rule.v4 IS '当前未使用';
  COMMENT ON COLUMN PUBLIC.casbin_rule.v5 IS '当前未使用';
  COMMIT;