-- 文件用途：
-- 用于保存总网后台用户的登录会话和 Access Token。
BEGIN;
  CREATE TABLE PUBLIC.sys_user_session (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 后台用户ID
    user_id BIGINT NOT NULL,
    -- Access Token原文
    access_token VARCHAR (2048) NOT NULL,
    -- Token到期时间
    expires_at TIMESTAMPTZ (3) NOT NULL,
    -- Token失效时间
    revoked_at TIMESTAMPTZ (3),
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sys_user_session PRIMARY KEY (id),
    CONSTRAINT fk_sys_user_session_user FOREIGN KEY (user_id) REFERENCES PUBLIC.sys_user (id) ON UPDATE RESTRICT ON DELETE CASCADE
  );

  -- Access Token全局唯一
  CREATE UNIQUE INDEX uk_sys_user_session_access_token ON PUBLIC.sys_user_session (access_token);

  -- 用于查询用户尚未主动失效的会话
  CREATE INDEX idx_sys_user_session_user_active ON PUBLIC.sys_user_session (user_id, expires_at)
  WHERE
    revoked_at IS NULL;
  COMMENT ON TABLE PUBLIC.sys_user_session IS '总网后台用户会话表';
  COMMENT ON COLUMN PUBLIC.sys_user_session.id IS '用户会话本地主键';
  COMMENT ON COLUMN PUBLIC.sys_user_session.user_id IS '后台用户ID';
  COMMENT ON COLUMN PUBLIC.sys_user_session.access_token IS 'Access Token原文';
  COMMENT ON COLUMN PUBLIC.sys_user_session.expires_at IS 'Token到期时间';
  COMMENT ON COLUMN PUBLIC.sys_user_session.revoked_at IS 'Token失效时间';
  COMMENT ON COLUMN PUBLIC.sys_user_session.created_at IS '创建时间';
  COMMIT;