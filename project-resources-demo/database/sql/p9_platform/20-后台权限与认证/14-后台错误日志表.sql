-- 文件用途：
-- 用于记录总网后台接口返回 5xx 时的请求和错误信息。
BEGIN;
  CREATE TABLE PUBLIC.sys_error_log (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 操作用户ID，未登录时为空
    user_id BIGINT,
    -- 所属 operator 的本地主键，总网或未登录为空
    operator_id BIGINT,
    -- HTTP请求方法
    request_method VARCHAR (10) NOT NULL,
    -- API请求路径
    request_path VARCHAR (500) NOT NULL,
    -- URL查询参数
    request_query TEXT,
    -- 脱敏后的请求内容
    request_body TEXT,
    -- 出错服务名
    service_name VARCHAR (100) NOT NULL,
    -- HTTP响应状态码
    response_status INTEGER NOT NULL,
    -- 脱敏后的响应内容
    response_body TEXT,
    -- 错误摘要
    subject TEXT,
    -- 错误堆栈
    detail TEXT,
    -- 请求耗时，单位毫秒
    duration_ms INTEGER NOT NULL DEFAULT 0,
    -- 客户端IP
    client_ip INET NOT NULL,
    -- 浏览器和设备标识
    user_agent VARCHAR (1000),
    -- 发生时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sys_error_log PRIMARY KEY (id),
    CONSTRAINT fk_sys_error_log_user FOREIGN KEY (user_id) REFERENCES PUBLIC.sys_user (id) ON UPDATE RESTRICT ON DELETE RESTRICT
  );

  -- 用于按时间查询错误日志
  CREATE INDEX idx_sys_error_log_time ON PUBLIC.sys_error_log (created_at DESC);

  -- 用于查询指定用户的错误日志
  CREATE INDEX idx_sys_error_log_user_time ON PUBLIC.sys_error_log (user_id, created_at DESC)
  WHERE
    user_id IS NOT NULL;

  -- 用于查询指定API的错误日志
  CREATE INDEX idx_sys_error_log_path_time ON PUBLIC.sys_error_log (request_path, created_at DESC);

  -- 用于按厅和时间查询错误日志
  CREATE INDEX idx_sys_error_log_operator_time ON PUBLIC.sys_error_log (operator_id, created_at DESC);

  -- 用于按服务和时间查询错误日志
  CREATE INDEX idx_sys_error_log_service_time ON PUBLIC.sys_error_log (service_name, created_at DESC);
  COMMENT ON TABLE PUBLIC.sys_error_log IS '总网后台错误日志表';
  COMMENT ON COLUMN PUBLIC.sys_error_log.id IS '错误日志本地主键';
  COMMENT ON COLUMN PUBLIC.sys_error_log.user_id IS '操作用户ID，未登录时为空';
  COMMENT ON COLUMN PUBLIC.sys_error_log.operator_id IS '所属operator的本地主键，总网或未登录为空';
  COMMENT ON COLUMN PUBLIC.sys_error_log.request_method IS 'HTTP请求方法';
  COMMENT ON COLUMN PUBLIC.sys_error_log.request_path IS 'API请求路径';
  COMMENT ON COLUMN PUBLIC.sys_error_log.request_query IS 'URL查询参数';
  COMMENT ON COLUMN PUBLIC.sys_error_log.request_body IS '脱敏后的请求内容';
  COMMENT ON COLUMN PUBLIC.sys_error_log.service_name IS '出错服务名';
  COMMENT ON COLUMN PUBLIC.sys_error_log.response_status IS 'HTTP响应状态码';
  COMMENT ON COLUMN PUBLIC.sys_error_log.response_body IS '脱敏后的响应内容';
  COMMENT ON COLUMN PUBLIC.sys_error_log.subject IS '错误摘要';
  COMMENT ON COLUMN PUBLIC.sys_error_log.detail IS '错误堆栈';
  COMMENT ON COLUMN PUBLIC.sys_error_log.duration_ms IS '请求耗时，单位毫秒';
  COMMENT ON COLUMN PUBLIC.sys_error_log.client_ip IS '客户端IP';
  COMMENT ON COLUMN PUBLIC.sys_error_log.user_agent IS '浏览器和设备标识';
  COMMENT ON COLUMN PUBLIC.sys_error_log.created_at IS '发生时间';
  COMMIT;
