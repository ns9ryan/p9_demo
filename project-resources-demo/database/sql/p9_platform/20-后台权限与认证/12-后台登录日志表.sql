-- 文件用途：
-- 用于记录总网后台用户的登录成功和登录失败日志。
BEGIN;
  CREATE TABLE PUBLIC.sys_login_log (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 后台用户ID，用户不存在时为空
    user_id BIGINT,
    -- 所属 operator 的本地主键，总网登录为空
    operator_id BIGINT,
    -- 本次登录输入的用户名
    username VARCHAR (64) NOT NULL,
    -- 登录结果：1成功，2失败
    login_result SMALLINT NOT NULL,
    -- 登录失败原因，登录成功时为空
    failure_reason VARCHAR (255),
    -- 登录IP
    login_ip INET NOT NULL,
    -- 设备ID
    device_id BIGINT,
    -- 浏览器和设备标识
    user_agent VARCHAR (1000),
    -- 登录时间
    login_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sys_login_log PRIMARY KEY (id),
    CONSTRAINT fk_sys_login_log_user FOREIGN KEY (user_id) REFERENCES PUBLIC.sys_user (id) ON UPDATE RESTRICT ON DELETE RESTRICT
  );

  -- 用于查询指定用户的登录记录
  CREATE INDEX idx_sys_login_log_user_time ON PUBLIC.sys_login_log (user_id, login_at DESC)
  WHERE
    user_id IS NOT NULL;

  -- 用于按登录结果和时间查询日志
  CREATE INDEX idx_sys_login_log_result_time ON PUBLIC.sys_login_log (login_result, login_at DESC);

  -- 用于按时间查询登录日志
  CREATE INDEX idx_sys_login_log_time ON PUBLIC.sys_login_log (login_at DESC);

  -- 用于按厅和时间查询登录日志
  CREATE INDEX idx_sys_login_log_operator_time ON PUBLIC.sys_login_log (operator_id, login_at DESC);
  COMMENT ON TABLE PUBLIC.sys_login_log IS '总网后台登录日志表';
  COMMENT ON COLUMN PUBLIC.sys_login_log.id IS '登录日志本地主键';
  COMMENT ON COLUMN PUBLIC.sys_login_log.user_id IS '后台用户ID，用户不存在时为空';
  COMMENT ON COLUMN PUBLIC.sys_login_log.operator_id IS '所属operator的本地主键，总网登录为空';
  COMMENT ON COLUMN PUBLIC.sys_login_log.username IS '本次登录输入的用户名';
  COMMENT ON COLUMN PUBLIC.sys_login_log.login_result IS '登录结果：1成功，2失败';
  COMMENT ON COLUMN PUBLIC.sys_login_log.failure_reason IS '登录失败原因';
  COMMENT ON COLUMN PUBLIC.sys_login_log.login_ip IS '登录IP';
  COMMENT ON COLUMN PUBLIC.sys_login_log.device_id IS '设备ID';
  COMMENT ON COLUMN PUBLIC.sys_login_log.user_agent IS '浏览器和设备标识';
  COMMENT ON COLUMN PUBLIC.sys_login_log.login_at IS '登录时间';
  COMMIT;