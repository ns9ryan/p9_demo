-- 文件用途：
-- 用于保存厅后台角色。
-- 每个角色只属于一个 operator，用于分配菜单权限和 Casbin API 权限。
BEGIN;
  CREATE TABLE PUBLIC.sys_role (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- 所属 operator 的本地主键
    operator_id BIGINT NOT NULL,
    -- 角色编码
    role_code VARCHAR (64) NOT NULL,
    -- 角色名称
    role_name VARCHAR (100) NOT NULL,
    -- 角色说明
    description VARCHAR (255),
    -- 角色状态：1正常，2停用
    status SMALLINT NOT NULL DEFAULT 1,
    -- 是否为系统内置角色
    is_system BOOLEAN NOT NULL DEFAULT FALSE,
    -- 展示顺序，数值越小越靠前
    sort_no INTEGER NOT NULL DEFAULT 0,
    -- 创建时间
    created_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 更新时间
    updated_at TIMESTAMPTZ (3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 软删除时间
    deleted_at TIMESTAMPTZ (3),
    CONSTRAINT pk_sys_role PRIMARY KEY (id)
  );

  -- 角色编码在同一个 operator 内不区分大小写唯一
  -- 已删除角色的角色编码不允许重新使用
  CREATE UNIQUE INDEX uk_sys_role_operator_code ON PUBLIC.sys_role (operator_id, LOWER(role_code));

  -- 未删除角色的角色名称在同一个 operator 内不区分大小写唯一
  CREATE UNIQUE INDEX uk_sys_role_operator_name ON PUBLIC.sys_role (operator_id, LOWER(role_name))
  WHERE
    deleted_at IS NULL;

  -- 用于按 operator 查询角色列表
  CREATE INDEX idx_sys_role_operator_status_sort ON PUBLIC.sys_role (operator_id, status, sort_no, id)
  WHERE
    deleted_at IS NULL;
  COMMENT ON TABLE PUBLIC.sys_role IS '厅后台角色表';
  COMMENT ON COLUMN PUBLIC.sys_role.id IS '角色本地主键';
  COMMENT ON COLUMN PUBLIC.sys_role.operator_id IS '所属operator的本地主键';
  COMMENT ON COLUMN PUBLIC.sys_role.role_code IS '角色编码';
  COMMENT ON COLUMN PUBLIC.sys_role.role_name IS '角色名称';
  COMMENT ON COLUMN PUBLIC.sys_role.description IS '角色说明';
  COMMENT ON COLUMN PUBLIC.sys_role.status IS '角色状态：1正常，2停用';
  COMMENT ON COLUMN PUBLIC.sys_role.is_system IS '是否为系统内置角色';
  COMMENT ON COLUMN PUBLIC.sys_role.sort_no IS '展示顺序，数值越小越靠前';
  COMMENT ON COLUMN PUBLIC.sys_role.created_at IS '创建时间';
  COMMENT ON COLUMN PUBLIC.sys_role.updated_at IS '更新时间';
  COMMENT ON COLUMN PUBLIC.sys_role.deleted_at IS '软删除时间';
  COMMIT;