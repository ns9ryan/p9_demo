CREATE TABLE game (
	id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
	game_code varchar(64) NOT NULL,
	source_game_code varchar(128) NOT NULL,
	source_id int8 NULL,
	category_id int8 NOT NULL,
	provider_id int8 NOT NULL,
	source_provider_key varchar(128) NULL,
	provider_key varchar(128) NULL,
	channel_id int8 NULL,
	"name" varchar(128) NULL,
	source_image_url varchar(512) NULL,
	image_url varchar(512) NULL,
	source_sort_no int4 NULL,
	sort_no int4 DEFAULT 0 NOT NULL,
	supports_embed bool DEFAULT false NOT NULL,
	supports_redirect bool DEFAULT false NOT NULL,
	source_status int2 NOT NULL,
	status int2 DEFAULT 1 NOT NULL,
	deleted_at timestamptz(3) NULL,
	created_at timestamptz(3) DEFAULT CURRENT_TIMESTAMP NOT NULL,
	updated_at timestamptz(3) DEFAULT CURRENT_TIMESTAMP NOT NULL,
	CONSTRAINT ck_game_game_code CHECK ((btrim((game_code)::text) <> ''::text)),
	CONSTRAINT ck_game_image_url CHECK (((image_url IS NULL) OR (btrim((image_url)::text) <> ''::text))),
	CONSTRAINT ck_game_sort_no CHECK ((sort_no >= 0)),
	CONSTRAINT ck_game_source_game_code CHECK ((btrim((source_game_code)::text) <> ''::text)),
	CONSTRAINT ck_game_source_image_url CHECK (((source_image_url IS NULL) OR (btrim((source_image_url)::text) <> ''::text))),
	CONSTRAINT ck_game_source_status CHECK ((source_status = ANY (ARRAY[1, 2]))),
	CONSTRAINT ck_game_status CHECK ((status = ANY (ARRAY[1, 2]))),
	CONSTRAINT game_pkey PRIMARY KEY (id)
);
CREATE INDEX idx_game_category_id ON public.game USING btree (category_id);
CREATE INDEX idx_game_channel_source_game_code ON public.game USING btree (channel_id, source_game_code) WHERE (channel_id IS NOT NULL);
CREATE INDEX idx_game_game_code ON public.game USING btree (game_code);
